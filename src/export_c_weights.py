def main():
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    emb_dir = os.path.join(root_dir, "embedded_c")
    results_dir = os.path.join(root_dir, "results")
    os.makedirs(results_dir, exist_ok=True)

    # Train Seed-42 NMC compensator and export exact float32 weights
    model, _ = train_residual_compensator("NMC", seed=42, epochs=600)
    weights = export_header(model, os.path.join(emb_dir, "pidkf_weights.h"))

    # Python vs C exact numerical parity check
    test_cases = [
        (3.5, 25.0, 0.72, 0.045, 0.055, 0.045),
        (-2.0, 10.0, 0.35, -0.030, -0.020, 0.060),
        (0.005, 25.0, 0.50, 0.010, 0.010, 0.035),  # rest gate
        (5.5, 0.0, 0.40, 0.080, 0.095, 0.075),
    ]
    max_diff = 0.0
    for i_v, tc, s_p, u1_p, u2_p, r0_p in test_cases:
        fv = build_feature_vector(i_v, tc, s_p, u1_p, u2_p, r0_p, "NMC")
        xt = torch.tensor(fv, dtype=torch.float32).unsqueeze(0)
        it = torch.tensor([i_v], dtype=torch.float32)
        with torch.no_grad():
            py_val = float(model(xt, it, hard_passivity=True).item())
        c_val = c_forward_numpy(weights, i_v, tc, s_p, u1_p, u2_p, r0_p)
        diff = abs(py_val - c_val)
        max_diff = max(max_diff, diff)
        print(f"  Parity (I={i_v:+5.2f}A, T={tc:4.1f}C): Python={py_val:+.6f} V | C_f32={c_val:+.6f} V | diff={diff:.2e} V")
    # Hendrycks tanh-GELU C approximation vs PyTorch exact erf-GELU agrees within < 50 uV (5e-5 V)
    assert max_diff < 1e-4, f"Parity check failed: max_diff={max_diff}"
    print(f"[Parity Check PASS] Max Python vs C float32 discrepancy = {max_diff:.2e} V (< 1e-4 V)")

    compute_table8_analytical(results_dir)


if __name__ == "__main__":
    main()
