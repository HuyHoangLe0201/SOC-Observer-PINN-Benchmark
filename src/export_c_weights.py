def c_forward_numpy(weights, i_val, temp_c, soc_prior, u1_prior, u2_prior, r0_est):
    """Exact mirror of embedded_c/pidkf.c PIDKF_NeuralCompensator_Forward in float32."""
    w1, b1, w2, b2, w3, b3 = weights
    x = np.array([
        np.float32(i_val / 4.0),
        np.float32((temp_c - 25.0) / 20.0),
        np.float32(soc_prior),
        np.float32(u1_prior * 15.0),
        np.float32(u2_prior * 15.0),
        np.float32((r0_est - 0.035) / 0.030),
    ], dtype=np.float32)

    def gelu_f32(v):
        v = np.float32(v)
        v3 = np.float32(v * v * v)
        inner = np.float32(0.7978845608) * (v + np.float32(0.044715) * v3)
        return np.float32(0.5) * v * (np.float32(1.0) + np.tanh(inner))

    h1 = np.array([gelu_f32(float(np.dot(w1[j], x) + b1[j])) for j in range(16)], dtype=np.float32)
    h2 = np.array([gelu_f32(float(np.dot(w2[j], h1) + b2[j])) for j in range(8)], dtype=np.float32)
    raw = float(np.float32(0.15) * np.float32(np.dot(w3, h2) + b3[0]))

    vmax = 0.015 + 0.022 * min(abs(i_val), 6.0)
    dv = float(np.clip(raw, -vmax, vmax))
    if abs(i_val) > 0.010 and (i_val * dv) > 0.0:
        dv = 0.0
    return dv


def export_header(model, out_path):
    sd = model.state_dict()
    # ResidualCompensatorMLP net layers: 0 (6->16), 1 (GELU), 2 (16->8), 3 (GELU), 4 (8->1)
    w1 = sd["net.0.weight"].detach().cpu().numpy().astype(np.float32)
    b1 = sd["net.0.bias"].detach().cpu().numpy().astype(np.float32)
    w2 = sd["net.2.weight"].detach().cpu().numpy().astype(np.float32)
    b2 = sd["net.2.bias"].detach().cpu().numpy().astype(np.float32)
    w3 = sd["net.4.weight"].detach().cpu().numpy().reshape(-1).astype(np.float32)
    b3 = sd["net.4.bias"].detach().cpu().numpy().reshape(-1).astype(np.float32)

    total_params = w1.size + b1.size + w2.size + b2.size + w3.size + b3.size
    assert total_params == 257, f"Expected 257 parameters, got {total_params}"

    def fmt_1d(arr):
        return ", ".join(f"{float(v):+.8e}f" for v in arr)

    def fmt_2d(mat):
        return ",\n    ".join("{ " + fmt_1d(row) + " }" for row in mat)

    lines = [
        "/**",
        " * @file pidkf_weights.h",
        " * @brief Exact exported IEEE-754 float32 weights for ResidualCompensatorMLP (Seed 42, NMC)",
        f" * @details Architecture 6->16->8->1 GELU MLP ({total_params} float32 params = {total_params * 4} bytes).",
        " *          Auto-generated by src/export_c_weights.py; DO NOT EDIT BY HAND.",
        " */",
        "#ifndef PIDKF_WEIGHTS_H",
        "#define PIDKF_WEIGHTS_H",
        "",
        f"#define PIDKF_NUM_PARAMS {total_params}",
        "",
        "static const float PIDKF_W1[16][6] = {",
        f"    {fmt_2d(w1)}",
        "};",
        f"static const float PIDKF_B1[16] = {{ {fmt_1d(b1)} }};",
        "",
        "static const float PIDKF_W2[8][16] = {",
        f"    {fmt_2d(w2)}",
        "};",
        f"static const float PIDKF_B2[8] = {{ {fmt_1d(b2)} }};",
        "",
        f"static const float PIDKF_W3[8] = {{ {fmt_1d(w3)} }};",
        f"static const float PIDKF_B3 = {float(b3[0]):+.8e}f;",
        "",
        "#endif /* PIDKF_WEIGHTS_H */",
        "",
    ]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"[Export] Wrote {total_params} float32 parameters ({total_params * 4} B) to {out_path}")
    return (w1, b1, w2, b2, w3, b3)


